import fc from "fast-check";
import { describe, expect, it } from "vitest";
import {
  canonicalHash,
  concurrentTransferBuggySpec,
  validateExecutionTrace,
  verifySpec,
  type StateValue,
} from "../src";

describe("Property-Based Tests (fast-check)", () => {
  it("canonicalHash is invariant under object key permutation", () => {
    const stateArb = fc.dictionary(
      fc.string({ minLength: 1, maxLength: 8 }),
      fc.oneof(fc.integer(), fc.boolean(), fc.string(), fc.constant(null))
    );

    fc.assert(
      fc.property(stateArb, (obj) => {
        const keys = Object.keys(obj);
        const reversed: Record<string, StateValue> = {};
        for (let i = keys.length - 1; i >= 0; i--) {
          reversed[keys[i]] = obj[keys[i]];
        }
        expect(canonicalHash(obj)).toBe(canonicalHash(reversed));
      })
    );
  });

  it("every counterexample prefix generated by BFS is a valid execution trace up to the violation", () => {
    const result = verifySpec(concurrentTransferBuggySpec);
    expect(result.status).toBe("INVARIANT_VIOLATED");
    if (result.status === "INVARIANT_VIOLATED") {
      // All states before the final violating step must pass trace validation
      const prefixBeforeViolation = result.counterexample
        .slice(0, -1)
        .map((s) => s.state);
      const traceCheck = validateExecutionTrace(
        concurrentTransferBuggySpec,
        prefixBeforeViolation
      );
      expect(traceCheck.valid).toBe(true);
    }
  });
});
